/**
 * Builds the single source of truth for every stable locator on the site.
 *
 * Scans pages/*.html for elements carrying data-testid, then emits:
 *   assets/js/locator-data.js   (loaded by pages/locator-reference.html)
 *   docs/locators.md            (human-readable table)
 *
 * Usage:  node scripts/build-locator-data.js
 */
const fs = require("fs");
const path = require("path");

const ROOT = path.join(__dirname, "..");
const PAGES_DIR = path.join(ROOT, "pages");

const PAGE_META = {
  "quick-practice.html": { title: "Quick Practice", section: "Start here" },
  "form-essentials.html": { title: "Form Essentials", section: "Form practice" },
  "dates-ranges.html": { title: "Dates & Ranges", section: "Form practice" },
  "files-buttons.html": { title: "Files & Buttons", section: "Form practice" },
  "wizard-submit.html": { title: "Wizard & Submit", section: "Form practice" },
  "behaviors.html": { title: "Interactions & Waits", section: "Behaviors" }
};

const TAG_RE = /<(input|select|textarea|button|a|div|span|iframe)\b([^>]*?)>/gi;
const ATTR_RE = /([\w:-]+)\s*=\s*"([^"]*)"/g;

function parseAttrs(raw) {
  const attrs = {};
  let m;
  ATTR_RE.lastIndex = 0;
  while ((m = ATTR_RE.exec(raw))) attrs[m[1].toLowerCase()] = m[2];
  return attrs;
}

function labelFor(html, id) {
  if (!id) return "";
  const re = new RegExp(
    "<label\\b[^>]*\\bfor=\"" + id.replace(/[.*+?^${}()|[\]\\]/g, "\\$&") + "\"[^>]*>([\\s\\S]*?)</label>",
    "i"
  );
  const m = html.match(re);
  if (!m) return "";
  return m[1]
    .replace(/<[^>]+>/g, "")
    .replace(/\s+/g, " ")
    .replace(/\s*\*\s*$/, "")
    .replace(/&amp;/g, "&")
    .replace(/&lt;/g, "<")
    .replace(/&gt;/g, ">")
    .replace(/&nbsp;/g, " ")
    .trim();
}

function collect(html, page) {
  const out = [];
  const seen = new Set();
  let m;
  TAG_RE.lastIndex = 0;
  while ((m = TAG_RE.exec(html))) {
    const tag = m[1].toLowerCase();
    const attrs = parseAttrs(m[2]);
    if (!attrs["data-testid"]) continue;
    const key = attrs["data-testid"];
    if (seen.has(key)) continue;
    seen.add(key);

    const label =
      labelFor(html, attrs.id) ||
      attrs["aria-label"] ||
      attrs["data-menu-label"] ||
      (tag === "button" ? (m[2].match(/>([^<]{1,60})</) || [])[1] || "" : "") ||
      attrs.placeholder ||
      "";

    out.push({
      page: page,
      tag: tag,
      id: attrs.id || "",
      name: attrs.name || "",
      testid: key,
      automationId: attrs["data-automation-id"] || "",
      type: attrs.type || "",
      label: String(label).trim(),
      role: attrs.role || "",
      disabled: /\bdisabled\b/.test(m[2])
    });
  }
  return out;
}

function bestLocator(e) {
  if (e.testid) return { strategy: "data-testid", value: e.testid };
  if (e.id) return { strategy: "id", value: e.id };
  if (e.name) return { strategy: "name", value: e.name };
  return { strategy: "css", value: e.tag };
}

function selenium(e) {
  const b = bestLocator(e);
  if (b.strategy === "id") return 'By.id("' + b.value + '")';
  if (b.strategy === "name") return 'By.name("' + b.value + '")';
  return 'By.css_selector("[data-testid=\'" + "' + b.value + '" + "\']")';
}

function playwright(e) {
  if (e.testid) return 'page.getByTestId("' + e.testid + '")';
  if (e.label) return 'page.getByLabel("' + e.label.replace(/"/g, "") + '")';
  if (e.id) return 'page.locator("#' + e.id + '")';
  return "page.locator('" + e.tag + "')";
}

/* ---------- run ---------- */
const rows = [];
for (const file of Object.keys(PAGE_META)) {
  const full = path.join(PAGES_DIR, file);
  if (!fs.existsSync(full)) continue;
  const html = fs.readFileSync(full, "utf8");
  rows.push(...collect(html, file));
}

rows.sort((a, b) =>
  a.page === b.page ? a.testid.localeCompare(b.testid) : a.page.localeCompare(b.page)
);

const payload = {
  generatedAt: new Date().toISOString(),
  total: rows.length,
  pages: Object.keys(PAGE_META).map((f) => ({
    file: f,
    title: PAGE_META[f].title,
    section: PAGE_META[f].section,
    count: rows.filter((r) => r.page === f).length
  })),
  rows: rows.map((r) => ({
    ...r,
    selenium: selenium(r),
    playwright: playwright(r)
  }))
};

/* ---------- emit JS ---------- */
const jsOut = path.join(ROOT, "assets", "js", "locator-data.js");
fs.mkdirSync(path.dirname(jsOut), { recursive: true });
fs.writeFileSync(
  jsOut,
  "/* AUTO-GENERATED by scripts/build-locator-data.js — do not edit by hand. */\n" +
    "window.LOCATOR_DATA = " +
    JSON.stringify(payload, null, 2) +
    ";\n",
  "utf8"
);

/* ---------- emit Markdown ---------- */
const mdDir = path.join(ROOT, "docs");
fs.mkdirSync(mdDir, { recursive: true });

let md =
  "# LocatorLab — Locator Reference\n\n" +
  "> AUTO-GENERATED by `scripts/build-locator-data.js`. Do not edit by hand — edit the HTML, then re-run the script.\n\n" +
  "Total stable targets: **" + payload.total + "**\n\n";

for (const p of payload.pages) {
  md += "\n## " + p.title + " (`pages/" + p.file + "`)\n\n";
  md += "| Element | id | name | data-testid | Selenium | Playwright |\n";
  md += "|---|---|---|---|---|---|\n";
  payload.rows
    .filter((r) => r.page === p.file)
    .forEach((r) => {
      const cell = (v) => (v ? "`" + v + "`" : "—");
      md +=
        "| " + (r.label || r.tag) +
        " (" + r.tag + (r.type ? "[" + r.type + "]" : "") + ") " +
        "| " + cell(r.id) +
        " | " + cell(r.name) +
        " | " + cell(r.testid) +
        " | " + cell(r.selenium) +
        " | " + cell(r.playwright) +
        " |\n";
    });
}

md +=
  "\n---\n\n## Locator contract\n\n" +
  "Every interactive element on this site carries:\n\n" +
  "1. a stable `id` (kebab-case)\n" +
  "2. a stable `name` (camelCase)\n" +
  "3. `data-testid` (same value as `id`)\n" +
  "4. `data-automation-id` (same value as `id`)\n" +
  "5. a real `<label for=\"…\">` or `aria-label`\n\n" +
  "Prefer `data-testid` in Playwright (`getByTestId`) and `id` in Selenium (`By.id`).\n" +
  "Use `getByLabel()` / `By.xpath(\"//label[...\]/following::input[1]\")` when you want to prove the label is wired correctly.\n";

fs.writeFileSync(path.join(mdDir, "locators.md"), md, "utf8");

console.log("locator-data.js :", path.relative(ROOT, jsOut));
console.log("locators.md     :", path.relative(ROOT, path.join(mdDir, "locators.md")));
console.log("rows generated  :", payload.total);
